# -*- coding: utf-8 -*-
"""
Field organizer: choose which fields FeatureNavEd shows.

Hiding or reordering fields here is a *view* setting of this panel only.
The layer's own attribute-form configuration is untouched, so the attribute
table, identify results and other forms are unaffected. The choices are
stored per layer as custom properties, which means they are saved with the
project.

Reordering applies to the multi-edit panel and to auto-generated native
forms. Forms built with the drag-and-drop designer or a .ui file keep the
designer's order.
"""

from qgis.PyQt.QtCore import Qt, pyqtSignal
from qgis.PyQt.QtWidgets import (
    QAbstractItemView, QGridLayout, QHBoxLayout, QLabel, QLineEdit,
    QListWidget, QListWidgetItem, QPushButton, QVBoxLayout, QWidget,
)
from qgis.core import Qgis, QgsEditFormConfig, QgsProject
from qgis.gui import QgsEditorWidgetWrapper

from .compat import CHECKED, UNCHECKED, USER_ROLE, qenum

HIDDEN_FIELDS_PROPERTY = "featurenaved/hidden_fields"
FIELD_ORDER_PROPERTY = "featurenaved/field_order"

# Marks widgets *we* hid, so un-hiding never reveals widgets that QGIS keeps
# hidden on purpose (e.g. constraint icons of unconstrained fields).
_HIDDEN_BY_US = "featurenaved_hidden"


# =============================================================================
# Persistence
# =============================================================================

def load_hidden_fields(layer):
    """Names of the fields hidden in FeatureNavEd for ``layer``."""
    if layer is None:
        return set()
    value = layer.customProperty(HIDDEN_FIELDS_PROPERTY, [])
    if not value:
        return set()
    if isinstance(value, str):      # a one-item list can come back as a str
        return {value}
    return {str(v) for v in value}


def save_hidden_fields(layer, names):
    names = sorted(names)
    if names == sorted(load_hidden_fields(layer)):
        return
    if names:
        layer.setCustomProperty(HIDDEN_FIELDS_PROPERTY, names)
    else:
        layer.removeCustomProperty(HIDDEN_FIELDS_PROPERTY)
    QgsProject.instance().setDirty(True)


def _string_list(value):
    if not value:
        return []
    if isinstance(value, str):      # a one-item list can come back as a str
        return [value]
    return [str(v) for v in value]


def load_field_order(layer):
    """Field names in the user's order (empty = the layer's own order)."""
    if layer is None:
        return []
    return _string_list(layer.customProperty(FIELD_ORDER_PROPERTY, []))


def save_field_order(layer, names):
    names = list(names)
    natural = [name for name, _, _ in organizable_fields(layer)]
    if names == natural:
        names = []
    if names == load_field_order(layer):
        return
    if names:
        layer.setCustomProperty(FIELD_ORDER_PROPERTY, names)
    else:
        layer.removeCustomProperty(FIELD_ORDER_PROPERTY)
    QgsProject.instance().setDirty(True)


def ordered_entries(entries, order):
    """Sort ``organizable_fields()`` entries by ``order``; fields missing
    from it (e.g. added later) follow in the layer's order."""
    rank = {name: i for i, name in enumerate(order)}
    indexed = list(enumerate(entries))
    indexed.sort(key=lambda item: (0, rank[item[1][0]]) if item[1][0] in rank
                 else (1, item[0]))
    return [entry for _, entry in indexed]


def uses_generated_layout(layer):
    """True for auto-generated forms (the only ones we can reorder)."""
    try:
        layout = layer.editFormConfig().layout()
    except Exception:
        return False
    enum = getattr(Qgis, 'AttributeFormLayout', None)
    if enum is not None and hasattr(enum, 'AutoGenerated') and layout == enum.AutoGenerated:
        return True
    generated = getattr(QgsEditFormConfig, 'GeneratedLayout', None)
    return generated is not None and layout == generated


def organizable_fields(layer):
    """``[(name, display_name, icon)]`` for the fields the forms can show."""
    entries = []
    if layer is None:
        return entries
    fields = layer.fields()
    for idx in range(fields.count()):
        if layer.editorWidgetSetup(idx).type() == 'Hidden':
            continue    # never shown in a form anyway
        icon = fields.iconForField(idx)
        entries.append((fields.at(idx).name(), layer.attributeDisplayName(idx), icon))
    return entries


# =============================================================================
# Native attribute form
# =============================================================================

def apply_to_attribute_form(form, layer, hidden_names):
    """Show/hide fields of a native ``QgsAttributeForm``.

    Works with auto-generated and drag-and-drop layouts: for every editor
    widget it hides the field's container, its label (found through the
    label's buddy) and, in auto-generated layouts, its constraint icon.
    Safe to call repeatedly; with no hidden fields it only restores what it
    hid before.
    """
    fields = layer.fields()
    hidden = {fields.indexOf(name) for name in hidden_names}
    hidden.discard(-1)
    labels = form.findChildren(QLabel)
    for wrapper in form.findChildren(QgsEditorWidgetWrapper):
        try:
            editor = wrapper.widget()
            idx = wrapper.fieldIdx()
        except RuntimeError:
            continue
        if editor is None:
            continue
        container = _field_container(editor, form)
        widgets = [container] + _labels_for(labels, editor, container)
        widgets.extend(_constraint_icons(container))
        _set_visible(widgets, idx not in hidden)


def apply_field_order(form, layer, order_names):
    """Re-stack the field rows of an auto-generated native form in
    ``order_names`` order (empty = the layer's own order).

    Each field occupies a block of grid rows (label, editor, constraint
    icon). Blocks are taken out and put back in the new order; nothing is
    rebuilt, so values and pending edits are untouched. Returns False and
    changes nothing for designed forms or unexpected layouts.
    """
    if not uses_generated_layout(layer):
        return False
    labels = form.findChildren(QLabel)
    grid = None
    blocks = {}                       # field index -> (first row, last row)
    for wrapper in form.findChildren(QgsEditorWidgetWrapper):
        try:
            editor = wrapper.widget()
            idx = wrapper.fieldIdx()
        except RuntimeError:
            continue
        if editor is None:
            continue
        container = _field_container(editor, form)
        parent = container.parentWidget()
        layout = parent.layout() if parent is not None else None
        if not isinstance(layout, QGridLayout) or (grid is not None and layout is not grid):
            return False
        grid = layout
        index = grid.indexOf(container)
        if idx in blocks or index < 0:
            return False
        row, _, row_span, _ = grid.getItemPosition(index)
        rows = [row, row + row_span - 1]
        for widget in _labels_for(labels, editor, container) + _constraint_icons(container):
            position = grid.indexOf(widget)
            if position >= 0:
                rows.append(grid.getItemPosition(position)[0])
        blocks[idx] = (min(rows), max(rows))
    if len(blocks) < 2:
        return grid is not None

    current = sorted(blocks, key=lambda idx: blocks[idx][0])
    first_row = blocks[current[0]][0]
    expected = first_row
    for idx in current:
        if blocks[idx][0] != expected:
            return False              # something else sits between fields
        expected = blocks[idx][1] + 1

    fields = layer.fields()
    rank = {fields.indexOf(name): i for i, name in enumerate(order_names)}
    wanted = sorted(blocks, key=lambda idx: (0, rank[idx]) if idx in rank else (1, idx))
    if wanted == current:
        return True

    taken = {idx: [] for idx in blocks}
    for i in reversed(range(grid.count())):
        row, col, row_span, col_span = grid.getItemPosition(i)
        for idx, (first, last) in blocks.items():
            if first <= row <= last:
                taken[idx].append((grid.takeAt(i), row - first, col, row_span, col_span))
                break
    row = first_row
    for idx in wanted:
        first, last = blocks[idx]
        for item, offset, col, row_span, col_span in taken[idx]:
            grid.addItem(item, row + offset, col, row_span, col_span)
        row += last - first + 1
    return True


def _labels_for(labels, editor, container):
    found = []
    for label in labels:
        buddy = label.buddy()
        if buddy is not None and (buddy is editor or buddy is container
                                  or container.isAncestorOf(buddy)):
            found.append(label)
    return found


def _field_container(editor, form):
    """The QgsAttributeFormEditorWidget wrapping ``editor`` (or the editor)."""
    parent = editor.parentWidget()
    while parent is not None and parent is not form:
        if parent.inherits("QgsAttributeFormEditorWidget"):
            return parent
        parent = parent.parentWidget()
    return editor


def _constraint_icons(container):
    """Constraint icon next to (or under, label-on-top) a field in the
    auto-generated layout's grid."""
    parent = container.parentWidget()
    layout = parent.layout() if parent is not None else None
    if not isinstance(layout, QGridLayout):
        return []
    index = layout.indexOf(container)
    if index < 0:
        return []
    row, col, row_span, _ = layout.getItemPosition(index)
    icons = []
    for r, c in ((row, col + 1), (row + row_span, col)):
        item = layout.itemAtPosition(r, c)
        widget = item.widget() if item is not None else None
        if widget is not None and widget.inherits("QSvgWidget"):
            icons.append(widget)
    return icons


def _set_visible(widgets, visible):
    for widget in widgets:
        if visible:
            if widget.property(_HIDDEN_BY_US):
                widget.setProperty(_HIDDEN_BY_US, False)
                widget.show()
        elif not widget.isHidden():
            widget.setProperty(_HIDDEN_BY_US, True)
            widget.hide()


# =============================================================================
# Organizer popup
# =============================================================================

class FieldOrganizer(QWidget):
    """Checkable, reorderable field list with a filter box, Show all /
    Hide all and Reset order.

    Changes apply immediately; :attr:`changed` is emitted after each one.
    """

    changed = pyqtSignal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self._loading = False
        self.setMinimumWidth(240)

        layout = QVBoxLayout(self)
        layout.setContentsMargins(6, 6, 6, 6)
        layout.setSpacing(4)

        title = QLabel("<b>Fields in the panel</b>")
        layout.addWidget(title)
        subtitle = QLabel("Tick to show \u00b7 drag to reorder")
        subtitle.setStyleSheet("color: gray;")
        layout.addWidget(subtitle)

        self.filter_edit = QLineEdit()
        self.filter_edit.setPlaceholderText("Filter fields…")
        self.filter_edit.setClearButtonEnabled(True)
        layout.addWidget(self.filter_edit)

        buttons = QHBoxLayout()
        buttons.setSpacing(4)
        self.show_all_btn = QPushButton("Show all")
        self.hide_all_btn = QPushButton("Hide all")
        for btn in (self.show_all_btn, self.hide_all_btn):
            btn.setToolTip("Applies to the fields listed below (respects the filter)")
            buttons.addWidget(btn)
        buttons.addStretch(1)
        self.count_label = QLabel()
        buttons.addWidget(self.count_label)
        layout.addLayout(buttons)

        self.list_widget = QListWidget()
        self.list_widget.setMinimumHeight(160)
        self.list_widget.setMaximumHeight(360)
        self.list_widget.setDragDropMode(
            qenum(QAbstractItemView, 'DragDropMode', 'InternalMove'))
        self.list_widget.setDefaultDropAction(qenum(Qt, 'DropAction', 'MoveAction'))
        layout.addWidget(self.list_widget)

        self.layout_note = QLabel(
            "This layer uses a designed form, so the order applies to "
            "multi-edit only.")
        self.layout_note.setStyleSheet("color: gray;")
        self.layout_note.setWordWrap(True)
        self.layout_note.setVisible(False)
        layout.addWidget(self.layout_note)

        footer = QHBoxLayout()
        hint = QLabel("Only affects this panel. Saved with the project.")
        hint.setStyleSheet("color: gray;")
        hint.setWordWrap(True)
        footer.addWidget(hint, 1)
        self.reset_order_btn = QPushButton("Reset order")
        self.reset_order_btn.setToolTip("Back to the layer's own field order")
        footer.addWidget(self.reset_order_btn)
        layout.addLayout(footer)

        self.filter_edit.textChanged.connect(self._apply_filter)
        self.show_all_btn.clicked.connect(lambda *_: self._set_listed(True))
        self.hide_all_btn.clicked.connect(lambda *_: self._set_listed(False))
        self.list_widget.itemChanged.connect(self._on_item_changed)
        self.list_widget.model().rowsMoved.connect(self._on_item_changed)
        self.reset_order_btn.clicked.connect(self._reset_order)
        self._natural = []
        self._entries = {}
        self._update_count()

    def set_fields(self, entries, hidden_names, order=(), designed_form=False):
        """Fill the list from ``organizable_fields()`` output."""
        self._natural = [name for name, _, _ in entries]
        self._entries = {entry[0]: entry for entry in entries}
        self.layout_note.setVisible(designed_form)
        self._populate(ordered_entries(entries, order), hidden_names)

    def _populate(self, entries, hidden_names):
        self._loading = True
        try:
            self.list_widget.clear()
            for name, display, icon in entries:
                text = display if display == name else f"{display}  ({name})"
                item = QListWidgetItem(text)
                if icon is not None and not icon.isNull():
                    item.setIcon(icon)
                item.setData(USER_ROLE, name)
                item.setToolTip(name)
                item.setCheckState(UNCHECKED if name in hidden_names else CHECKED)
                self.list_widget.addItem(item)
        finally:
            self._loading = False
        self._apply_filter(self.filter_edit.text())
        self._update_count()

    def hidden_fields(self):
        return {self._item(i).data(USER_ROLE)
                for i in range(self.list_widget.count())
                if self._item(i).checkState() != CHECKED}

    def field_order(self):
        return [self._item(i).data(USER_ROLE) for i in range(self.list_widget.count())]

    def _reset_order(self):
        hidden = self.hidden_fields()
        self._populate([self._entries[name] for name in self._natural], hidden)
        self.changed.emit()

    def _item(self, row):
        return self.list_widget.item(row)

    def _apply_filter(self, text):
        needle = text.strip().lower()
        for i in range(self.list_widget.count()):
            item = self._item(i)
            self.list_widget.setRowHidden(i, bool(needle) and needle not in item.text().lower())

    def _set_listed(self, visible):
        state = CHECKED if visible else UNCHECKED
        self._loading = True
        try:
            for i in range(self.list_widget.count()):
                if not self.list_widget.isRowHidden(i):
                    self._item(i).setCheckState(state)
        finally:
            self._loading = False
        self._update_count()
        self.changed.emit()

    def _on_item_changed(self, *args):
        if self._loading:
            return
        self._update_count()
        self.changed.emit()

    def _update_count(self):
        total = self.list_widget.count()
        shown = total - len(self.hidden_fields())
        self.count_label.setText(f"{shown} / {total} shown")
